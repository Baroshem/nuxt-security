import { describe, it, expect } from 'vitest'
import { injectNonceToTags } from '../src/utils/nonce'

const nonce = 'abc123'

describe('[nuxt-security] injectNonceToTags', () => {
  it('adds the nonce to link, script and style tags', () => {
    const html = '<link rel="stylesheet" href="/a.css"><script src="/a.js"></script><style>a{}</style>'

    expect(injectNonceToTags(html, nonce)).toBe(
      '<link nonce="abc123" rel="stylesheet" href="/a.css">'
      + '<script nonce="abc123" src="/a.js"></script>'
      + '<style nonce="abc123">a{}</style>'
    )
  })

  it('matches tag names regardless of case and keeps them as written', () => {
    expect(injectNonceToTags('<SCRIPT src="/a.js"></SCRIPT>', nonce))
      .toBe('<SCRIPT nonce="abc123" src="/a.js"></SCRIPT>')
  })

  it('keeps self-closing tags and single-quoted attributes', () => {
    expect(injectNonceToTags(`<link rel='preload' href='/a.js'/>`, nonce))
      .toBe(`<link nonce="abc123" rel='preload' href='/a.js'/>`)
  })

  it('replaces an existing nonce on any of the three tags', () => {
    const html = '<link nonce="old" rel="x"><script src="/a.js" nonce="old"></script><style nonce="old"></style>'

    expect(injectNonceToTags(html, nonce)).toBe(
      '<link nonce="abc123" rel="x"><script src="/a.js" nonce="abc123"></script><style nonce="abc123"></style>'
    )
  })

  it('does not treat other attributes ending with nonce as the nonce', () => {
    expect(injectNonceToTags('<script data-nonce="old"></script>', nonce))
      .toBe('<script nonce="abc123" data-nonce="old"></script>')
  })

  it('does not modify custom elements or tags that only start with a known name', () => {
    const html = '<scripter></scripter><script-like></script-like><linked-list></linked-list><styled-box></styled-box>'

    expect(injectNonceToTags(html, nonce)).toBe(html)
  })

  it('does not modify tags inside attribute values', () => {
    const html = '<div class="<script>no nonce" title=\'<link rel="x">\'>Hello</div>'

    expect(injectNonceToTags(html, nonce)).toBe(html)
  })

  it('does not modify tags inside comments', () => {
    const html = '<!-- <script src="/a.js"></script> --><script src="/b.js"></script>'

    expect(injectNonceToTags(html, nonce))
      .toBe('<!-- <script src="/a.js"></script> --><script nonce="abc123" src="/b.js"></script>')
  })

  it('does not modify tags written inside a script', () => {
    const html = '<script>document.write("<script src=x></script>")</script><link rel="x">'

    expect(injectNonceToTags(html, nonce))
      .toBe('<script nonce="abc123">document.write("<script src=x></script>")</script><link nonce="abc123" rel="x">')
  })

  it('handles a `>` inside a quoted attribute value', () => {
    expect(injectNonceToTags('<script data-x="a>b" src="/a.js"></script>', nonce))
      .toBe('<script nonce="abc123" data-x="a>b" src="/a.js"></script>')
  })

  // https://github.com/Baroshem/nuxt-security/issues/760
  describe('quote characters in CSS', () => {
    // Class selectors generated by Tailwind for arbitrary values, such as bg-[url("/image.svg")]
    const css = '.bg-\\[url\\(\\"\\/image\\.svg\\"\\)\\]{background-image:url("/image.svg")}'
    const content = '.before\\:content-\\[\\"x\\"\\]::before{content:"x"} .a\\"b{color:red}'

    it.each([css, content, `${css}${content}`, '.a\\\'b{color:red}', '.a\\"{color:red}'])(
      'adds the nonce to every tag that follows a style with `%s`',
      (style) => {
        const html = `<style>${style}</style>`
          + '<link rel="modulepreload" as="script" crossorigin href="/_nuxt/a.js">'
          + '<script type="module" src="/_nuxt/b.js" crossorigin></script>'
          + '<link rel="prefetch" as="script" crossorigin href="/_nuxt/c.js">'

        expect(injectNonceToTags(html, nonce)).toBe(
          `<style nonce="abc123">${style}</style>`
          + '<link nonce="abc123" rel="modulepreload" as="script" crossorigin href="/_nuxt/a.js">'
          + '<script nonce="abc123" type="module" src="/_nuxt/b.js" crossorigin></script>'
          + '<link nonce="abc123" rel="prefetch" as="script" crossorigin href="/_nuxt/c.js">'
        )
      }
    )

    it('does not pair the quote of a style with a quote in a later attribute', () => {
      const html = `<style>${css}</style><script src="/a.js"></script><div class="x">y</div><script src="/b.js"></script>`

      expect(injectNonceToTags(html, nonce)).toBe(
        `<style nonce="abc123">${css}</style><script nonce="abc123" src="/a.js"></script>`
        + '<div class="x">y</div><script nonce="abc123" src="/b.js"></script>'
      )
    })
  })

  it('leaves an unterminated tag alone', () => {
    expect(injectNonceToTags('<script src="/a.js', nonce)).toBe('<script src="/a.js')
  })

  it('returns non-string elements untouched', () => {
    const element = { tag: 'script' } as unknown as string

    expect(injectNonceToTags(element, nonce)).toBe(element)
  })

  it('stays fast on long input without a closing bracket', () => {
    const html = `<script ${'a = '.repeat(20000)}`
    const start = performance.now()

    expect(injectNonceToTags(html, nonce)).toBe(html)
    expect(performance.now() - start).toBeLessThan(1000)
  })
})
